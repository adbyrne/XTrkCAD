#!/bin/sh
# Run a test command with core dumps on, and print a backtrace of every core
# a crash left behind. For CI's Linux test jobs: an intermittent crash then
# shows where it happened, in the job's log.
#
# usage: tools/ctest-with-backtraces.sh <command> [args...]
#        (e.g. tools/ctest-with-backtraces.sh ctest --test-dir build -L regression-ci)
#
# Cores go to $RUNNER_TEMP/cores (or /tmp/cores). The core size limit is per
# process, so it is raised here, in the same shell that starts the tests;
# kernel.core_pattern needs root (sudo on GitHub's runners) and is skipped
# with a note when that isn't available. gdb is installed only when a core
# is found. The command's own exit status is returned.

cores="${RUNNER_TEMP:-/tmp}/cores"
mkdir -p "$cores"
ulimit -c unlimited 2>/dev/null || echo "note: can't raise the core size limit"
if [ "$(uname)" = Linux ]; then
	sudo -n sysctl -q -w kernel.core_pattern="$cores/core.%e.%p" 2>/dev/null ||
		echo "note: kernel.core_pattern not set; cores go wherever the system puts them"
fi

"$@"
code=$?

found=0
for core in "$cores"/core.*; do
	[ -e "$core" ] || continue
	if [ $found -eq 0 ]; then
		found=1
		if ! command -v gdb >/dev/null 2>&1; then
			sudo -n apt-get update -q >/dev/null 2>&1
			sudo -n apt-get install -y -q gdb >/dev/null 2>&1 ||
				echo "note: gdb couldn't be installed"
		fi
	fi
	exe=$(gdb -batch -c "$core" 2>/dev/null |
		sed -n "s/^Core was generated by \`\([^ ']*\).*/\1/p")
	# A command started by name (not path) is looked up the way the shell would.
	case "$exe" in
	*/*) ;;
	?*) exe=$(command -v "$exe" 2>/dev/null || echo "$exe") ;;
	esac
	echo "--- backtrace: $core (${exe:-executable unknown}) ---"
	if [ -n "$exe" ] && [ -f "$exe" ]; then
		gdb -batch -q -ex "thread apply all bt" "$exe" "$core" 2>&1 |
			grep -v '^\[New LWP'
	else
		gdb -batch -q -ex "thread apply all bt" -c "$core" 2>&1 | grep -v '^\[New LWP'
	fi
done
exit $code
